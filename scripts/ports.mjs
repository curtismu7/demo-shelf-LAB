#!/usr/bin/env node
// Usage: node scripts/ports.mjs        (writes docs/ports.md from the registry: data/demos.json + .data/demos.local.json)
// The table of which ports are taken and by whom, and which 50-port blocks are open.
// node scripts/ports.mjs --next [n]   prints the next n free ports (default 1) in the packed range for new apps; writes nothing.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { loadRegistry } from '../server/src/registry.js';
import { PACKED_RANGE, RESERVED_PORTS, nextFreePorts, packedRangeSummary } from './ports-lib.mjs';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const demos = loadRegistry({
  seedFile: path.join(root, 'data/demos.json'),
  localFile: path.join(root, '.data/demos.local.json'),
  allowedHosts: [],
  demoRoot: process.env.SHELF_DEMO_ROOT || path.dirname(root),
});
const rows = demos
  .filter((d) => d.url)
  .map((d) => ({ port: Number(new URL(d.url).port), id: d.id, name: d.name, cat: d.catalogId || '', mock: d.where === 'mock', compose: d.composeFile || '' }))
  .filter((r) => r.port)
  .sort((a, b) => a.port - b.port || a.id.localeCompare(b.id));
const nextArg = process.argv.indexOf('--next');
if (nextArg !== -1) {
  const raw = process.argv[nextArg + 1];
  const count = raw === undefined ? 1 : Number(raw);
  try { console.log(nextFreePorts(rows.map((r) => r.port), count).join('\n')); } catch (e) { console.error(`ports: ${e.message}`); process.exit(1); }
  process.exit(0);
}
const by = new Map();
for (const r of rows) by.set(r.port, [...(by.get(r.port) || []), r]);
// Two cards that share one compose file are ONE app listed twice (mcp-tools and mcp-scanner on 4810): not a clash.
const rivals = (r) => by.get(r.port).filter((o) => o.id !== r.id && !(o.compose && o.compose === r.compose));

const LO = 4500, HI = 7999, BLOCK = 50;
const blocks = [];
for (let b = LO; b <= HI; b += BLOCK) {
  const users = [...new Set(rows.filter((r) => r.port >= b && r.port < b + BLOCK).map((r) => r.id))];
  blocks.push(`| ${b}-${b + BLOCK - 1} | ${users.length ? users.join(', ') : '**open**'} |`);
}
const packed = packedRangeSummary(rows.map((r) => r.port));
const out = [
  '# Ports',
  '',
  'Generated by `npm run ports` from the registry (`data/demos.json` and `.data/demos.local.json`). Do not edit by hand.',
  '',
  '## New apps: one port each, from the packed range',
  '',
  `New standalone apps take ports ${PACKED_RANGE.lo}-${PACKED_RANGE.hi}, one at a time: run \`npm run ports -- --next\` for the next free one, then register the app in data/demos.json. Declare only the ports the app really uses, not a block. Existing apps keep the ports they have.`,
  '',
  `Packed range: ${packed.inUse} of ${packed.size} in use, ${packed.free} free.`,
  '',
  '## Reserved by shared infrastructure',
  '',
  'Not shelf apps, so not in the registry; the allocator skips them.',
  '',
  '| Port | Used by |',
  '| --- | --- |',
  ...Object.entries(RESERVED_PORTS).map(([port, who]) => `| ${port} | ${who} |`),
  '',
  '## Taken',
  '',
  '| Port | App | Catalog | |',
  '| --- | --- | --- | --- |',
  ...rows.map((r) => `| ${r.port} | ${r.id} | ${r.cat} | ${rivals(r).length ? '**CLASH** with ' + rivals(r).map((o) => o.id).join(', ') : ''} |`),
  '',
  `## Blocks of ${BLOCK} (${LO}-${HI})`,
  '',
  '| Block | Taken by |',
  '| --- | --- |',
  ...blocks,
  '',
];
fs.writeFileSync(path.join(root, 'docs/ports.md'), out.join('\n'));
const clashes = new Set(rows.filter((r) => rivals(r).length).map((r) => r.port)).size;
console.log(`ports: ${rows.length} apps, ${clashes} clashing port(s) -> docs/ports.md`);
