#!/usr/bin/env node
// Usage: node scripts/ports.mjs        (writes docs/ports.md from the registry: data/demos.json + .data/demos.local.json)
// The table of which ports are taken and by whom, and which 50-port blocks are open.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { loadRegistry } from '../server/src/registry.js';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const demos = loadRegistry({
  seedFile: path.join(root, 'data/demos.json'),
  localFile: path.join(root, '.data/demos.local.json'),
  allowedHosts: [],
  demoRoot: process.env.SHELF_DEMO_ROOT || path.dirname(root),
});
const rows = demos
  .filter((d) => d.url)
  .map((d) => ({ port: Number(new URL(d.url).port), id: d.id, name: d.name, cat: d.catalogId || '', mock: d.where === 'mock' }))
  .filter((r) => r.port)
  .sort((a, b) => a.port - b.port || a.id.localeCompare(b.id));
const by = new Map();
for (const r of rows) by.set(r.port, [...(by.get(r.port) || []), r]);

const LO = 4500, HI = 7999, BLOCK = 50;
const blocks = [];
for (let b = LO; b <= HI; b += BLOCK) {
  const users = [...new Set(rows.filter((r) => r.port >= b && r.port < b + BLOCK).map((r) => r.id))];
  blocks.push(`| ${b}-${b + BLOCK - 1} | ${users.length ? users.join(', ') : '**open**'} |`);
}
const out = [
  '# Ports',
  '',
  'Generated by `npm run ports` from the registry (`data/demos.json` and `.data/demos.local.json`). Do not edit by hand.',
  '',
  '## Taken',
  '',
  '| Port | App | Catalog | |',
  '| --- | --- | --- | --- |',
  ...rows.map((r) => `| ${r.port} | ${r.id} | ${r.cat} | ${by.get(r.port).length > 1 ? '**CLASH** with ' + by.get(r.port).filter((o) => o.id !== r.id).map((o) => o.id).join(', ') : ''} |`),
  '',
  `## Blocks of ${BLOCK} (${LO}-${HI})`,
  '',
  '| Block | Taken by |',
  '| --- | --- |',
  ...blocks,
  '',
];
fs.writeFileSync(path.join(root, 'docs/ports.md'), out.join('\n'));
const clashes = [...by.values()].filter((v) => v.length > 1).length;
console.log(`ports: ${rows.length} apps, ${clashes} clashing port(s) -> docs/ports.md`);
